@pytest.fixture(autouse=True)
def clean_db():
    """Migrations manage their own schema; do not create the global test models."""


@pytest.fixture
async def migration_db(db_type, tmp_path):
    url = (
        f"sqlite+aiosqlite:///{tmp_path / 'migrations%example.db'}"
        if db_type == "sqlite"
        else TestDatabaseConfig.get_config(db_type)["url"]
    )
    db = await init_db(url, name="migrations", is_default=False)
    try:
        yield db
    finally:
        async with db.engine.begin() as connection:

            def cleanup(sync_connection):
                metadata = sa.MetaData()
                metadata.reflect(
                    sync_connection,
                    only=lambda name, _: (
                        name
                        in {"migration_accounts", "migration_example_version", "migration_obsolete", "unrelated_table"}
                    ),
                )
                metadata.drop_all(sync_connection)

            await connection.run_sync(cleanup)
        await close_db("migrations")


def config_for(directory=EXAMPLE, output=None):
    return Config(str(directory / "alembic.ini"), output_buffer=output)


def run_command(connection, operation, *args, config=None, **kwargs):
    config = config or config_for()
    config.attributes["connection"] = connection
    try:
        return operation(config, *args, **kwargs)
    finally:
        config.attributes.pop("connection", None)


async def test_upgrade_backfills_existing_rows_and_matches_model(migration_db):
    async with migration_db.engine.begin() as connection:
        await connection.run_sync(run_command, command.upgrade, FIRST)
        await connection.execute(sa.text("INSERT INTO migration_accounts (email) VALUES ('old@example.com')"))
        await connection.run_sync(run_command, command.upgrade, "head")
        row = (await connection.execute(sa.text("SELECT email, display_name FROM migration_accounts"))).one()
        assert tuple(row) == ("old@example.com", "old@example.com")
        await connection.run_sync(run_command, command.check)

        def check_schema(sync_connection):
            inspector = sa.inspect(sync_connection)
            columns = {column["name"]: column for column in inspector.get_columns("migration_accounts")}
            assert columns["display_name"]["nullable"] is False
            assert "ix_migration_accounts_display_name" in {
                index["name"] for index in inspector.get_indexes("migration_accounts")
            }

        await connection.run_sync(check_schema)

    stored = await MigrationAccount.objects.using("migrations").create(email="new@example.com", display_name="New")
    assert stored.id is not None
    assert (await MigrationAccount.objects.using("migrations").get(id=stored.id)).display_name == "New"
    with pytest.raises(IntegrityError):
        await MigrationAccount.objects.using("migrations").create(email="new@example.com", display_name="Duplicate")


async def test_downgrade_preserves_old_columns_and_can_upgrade_again(migration_db):
    async with migration_db.engine.begin() as connection:
        await connection.run_sync(run_command, command.upgrade, "head")
        await connection.execute(
            sa.text("INSERT INTO migration_accounts (email, display_name) VALUES ('keep@example.com', 'Keep')")
        )
        await connection.run_sync(run_command, command.downgrade, FIRST)
        assert (await connection.execute(sa.text("SELECT email FROM migration_accounts"))).scalar_one() == (
            "keep@example.com"
        )
        await connection.run_sync(run_command, command.upgrade, "head")
        assert (await connection.execute(sa.text("SELECT display_name FROM migration_accounts"))).scalar_one() == (
            "keep@example.com"
        )
        await connection.run_sync(run_command, command.downgrade, "base")
        assert not await connection.run_sync(lambda conn: sa.inspect(conn).has_table("migration_accounts"))


async def test_autogenerate_detects_changes_and_ignores_unrelated_tables(migration_db, tmp_path):
    directory = tmp_path / "example"
    shutil.copytree(EXAMPLE, directory, ignore=shutil.ignore_patterns("*.db", "*.db-*", "__pycache__"))
    config = config_for(directory)
    extra_column = sa.Column("nickname", sa.String(40), nullable=True)
    async with migration_db.engine.begin() as connection:
        await connection.run_sync(run_command, command.upgrade, "head", config=config)
        await connection.execute(sa.text("CREATE TABLE unrelated_table (id INTEGER PRIMARY KEY)"))
        # The isolated registry and ownership filter avoid removing unrelated tables.
        await connection.run_sync(run_command, command.check, config=config)
        MigrationAccount.__table__.append_column(extra_column)
        try:
            with pytest.raises(AutogenerateDiffsDetected):
                await connection.run_sync(run_command, command.check, config=config)
            await connection.run_sync(
                run_command,
                command.revision,
                message="add nickname",
                autogenerate=True,
                rev_id="0003_nickname",
                config=config,
            )
            await connection.run_sync(run_command, command.upgrade, "head", config=config)
            await connection.run_sync(run_command, command.check, config=config)
            await connection.run_sync(run_command, command.downgrade, HEAD, config=config)
        finally:
            MigrationAccount.__table__._columns.remove(extra_column)
        await connection.run_sync(run_command, command.check)


async def test_server_default_changes_are_not_suppressed(migration_db):
    async with migration_db.engine.begin() as connection:
        await connection.run_sync(run_command, command.upgrade, "head")
        column = MigrationAccount.__table__.c.display_name
        previous_default = column.server_default
        column.server_default = sa.DefaultClause("Anonymous")
        try:
            with pytest.raises(AutogenerateDiffsDetected):
                await connection.run_sync(run_command, command.check)
        finally:
            column.server_default = previous_default


