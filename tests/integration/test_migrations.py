async def test_cli_runs_from_another_directory_with_environment_url(migration_db, tmp_path):
    # Percent in the SQLite filename also covers ConfigParser interpolation pitfalls.
    url = migration_db.engine.url.render_as_string(hide_password=False)
    env = {**os.environ, "SQLOBJECTS_MIGRATION_URL": url}
    for args in [("upgrade", "head"), ("check",), ("downgrade", "base")]:
        process = await asyncio.create_subprocess_exec(
            sys.executable,
            "-m",
            "alembic",
            "-c",
            str(EXAMPLE / "alembic.ini"),
            *args,
            cwd=tmp_path,
            env=env,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            stdout, stderr = await asyncio.wait_for(process.communicate(), timeout=30)
        finally:
            if process.returncode is None:
                process.kill()
                await process.wait()
        assert process.returncode == 0, (stdout + stderr).decode()
    async with migration_db.engine.connect() as connection:
        assert not await connection.run_sync(lambda conn: sa.inspect(conn).has_table("migration_accounts"))


@pytest.mark.parametrize("url", ["sqlite+aiosqlite://", "postgresql+asyncpg://", "mysql+aiomysql://"])
async def test_offline_sql_requires_no_connection(url, monkeypatch):
    monkeypatch.setenv("SQLOBJECTS_MIGRATION_URL", url)
    output = io.StringIO()
    config = config_for(output=output)
    with patch("sqlalchemy.ext.asyncio.create_async_engine", side_effect=AssertionError("offline connection")):
        command.upgrade(config, "head", sql=True)
        upgrade_sql = output.getvalue()
        output.seek(0)
        output.truncate()
        command.downgrade(config, f"{HEAD}:base", sql=True)
        downgrade_sql = output.getvalue()
    assert "CREATE TABLE migration_accounts" in upgrade_sql
    assert "UPDATE migration_accounts SET display_name=migration_accounts.email" in upgrade_sql
    assert "DROP TABLE migration_accounts" in downgrade_sql
    if url.startswith("sqlite"):
        with sqlite3.connect(":memory:") as connection:
            connection.executescript(upgrade_sql)
            assert connection.execute("SELECT version_num FROM migration_example_version").fetchone() == (HEAD,)
            connection.executescript(downgrade_sql)
            assert (
                connection.execute("SELECT name FROM sqlite_master WHERE name='migration_accounts'").fetchone() is None
            )


